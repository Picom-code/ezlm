#!/usr/bin/env python3
"""Assemble the T13 beta docs from agents/T13/sections/*.md.

Sections are named after the agent that writes them (a01.md ... a13.md) and are
merged in numeric order:

    a01-a08 -> BETA.md             (the guide, in reading order)
    a09-a12 -> TROUBLESHOOTING.md  (one entry per real message)
    a13     -> FAQ.md

Every TROUBLESHOOTING entry must have three parts: the message, what it means,
and what to do. The script checks them and reports the gaps. It exits 0 when the
documents were written, even with gaps, so the Lead can assemble partial work;
pass --strict (or --check) to exit 1 when anything is missing.

Entry format (a09 to a12)
--------------------------
    ## "Windows protected your PC"

    **Message:** Windows protected your PC
    **What it means:** This beta is not code-signed yet, so SmartScreen warns.
    **What to do:** Click More info, then Run anyway.

The heading counts as the message when it quotes the text, so the **Message:**
line is optional. Labels are matched loosely: "What it means", "Why it
happens" and "Cause" all count as the meaning; "What to do", "Fix" and "Next
step" all count as the action. A three-column markdown table with Message,
What it means and What to do headers also works, if the section has no entry
headings.

Run it from anywhere:

    python3 agents/T13/assemble.py            # write the three documents
    python3 agents/T13/assemble.py --check    # validate only, exit 1 on gaps
    python3 agents/T13/assemble.py --report agents/T13/a15/assembly-report.md

The script is idempotent: running it twice writes the same bytes, so a rerun
does not create an empty commit.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

GUIDE_IDS = ["a%02d" % i for i in range(1, 9)]
TROUBLE_IDS = ["a%02d" % i for i in range(9, 13)]
FAQ_IDS = ["a13"]

HEADER_COMMENT = (
    "<!-- Generated by agents/T13/assemble.py from agents/T13/sections. "
    "Edit the section, not this file. -->"
)

HEADING_RE = re.compile(r"^(#{1,6})[ \t]+(.*?)[ \t]*#*[ \t]*$")
FENCE_RE = re.compile(r"^[ \t]*(`{3,}|~{3,})")
LABEL_RE = re.compile(
    r"^[ \t]*(?:[-*+>][ \t]+|\d+[.)][ \t]+)?"
    r"(?:#{1,6}[ \t]+)?"
    r"(?:\*\*|__|\*|_)?[ \t]*"
    r"([A-Za-z][A-Za-z0-9 /'’&()-]{1,40}?)"
    r"[ \t]*(?:\*\*|__|\*|_)?[ \t]*:[ \t]*"
    r"(.*)$"
)
LABEL_ONLY_RE = re.compile(
    r"^[ \t]*(?:[-*+>][ \t]+|\d+[.)][ \t]+)?"
    r"(?:#{1,6}[ \t]+)?"
    r"(?:\*\*|__)[ \t]*"
    r"([A-Za-z][A-Za-z0-9 /'’&()-]{1,40}?)"
    r"[ \t]*(?:\*\*|__)[ \t]*$"
)
QUOTE_RE = re.compile(r"[\"“”`]")

ALIASES = {
    "message": "message",
    "the message": "message",
    "exact message": "message",
    "error message": "message",
    "error": "message",
    "what you see": "message",
    "what you'll see": "message",
    "you see": "message",
    "what it says": "message",
    "what appears": "message",
    "symptom": "message",
    "symptoms": "message",
    "text on screen": "message",
    "what it means": "meaning",
    "what it means in plain words": "meaning",
    "meaning": "meaning",
    "why": "meaning",
    "why it happens": "meaning",
    "why it happened": "meaning",
    "why you see it": "meaning",
    "cause": "meaning",
    "what happened": "meaning",
    "explanation": "meaning",
    "what to do": "action",
    "what to do next": "action",
    "what you can do": "action",
    "what to try": "action",
    "action": "action",
    "fix": "action",
    "how to fix": "action",
    "to fix": "action",
    "next step": "action",
    "next steps": "action",
    "resolution": "action",
    "solution": "action",
    "workaround": "action",
    "do this": "action",
    "try this": "action",
}

PART_NAMES = {"message": "the message", "meaning": "what it means", "action": "what to do"}

# Headings that are a section title rather than the message itself.
GENERIC_HEADINGS = {
    "troubleshooting",
    "error messages",
    "errors",
    "common errors",
    "common problems",
    "problems",
    "overview",
    "notes",
    "introduction",
    "engine errors",
    "other errors",
    "the short version",
}

TABLE_SEPARATOR_RE = re.compile(r"^[ \t]*\|?[ \t:|-]+\|?[ \t]*$")


@dataclass
class Doc:
    filename: str
    title: str
    intro: str
    ids: List[str]
    rule: bool


DOCS = [
    Doc(
        "BETA.md",
        "# EZLM beta tester guide",
        "EZLM runs an AI model on your own computer and gives you a web address and key "
        "that other apps can use. This guide takes you from install to your first chat. "
        "If a message stops you, look it up in TROUBLESHOOTING.md.",
        GUIDE_IDS,
        True,
    ),
    Doc(
        "TROUBLESHOOTING.md",
        "# Troubleshooting",
        "Find the message you saw. Each entry gives the exact text, what it means, "
        "and what to do.",
        TROUBLE_IDS,
        False,
    ),
    Doc(
        "FAQ.md",
        "# Frequently asked questions",
        "Short answers to what testers ask most.",
        FAQ_IDS,
        True,
    ),
]


@dataclass
class Entry:
    source: Path
    line: int
    heading: str
    missing: List[str] = field(default_factory=list)


@dataclass
class Section:
    sid: str
    path: Path
    text: str


def normalize_label(value: str) -> str:
    value = value.replace("’", "'").replace("`", "")
    value = value.strip().strip("*_").strip()
    value = value.rstrip(":.!?").strip()
    return re.sub(r"\s+", " ", value).lower()


def normalize_heading(value: str) -> str:
    value = value.replace("’", "'").replace("`", "")
    value = value.strip().strip("*_").strip()
    value = value.rstrip(":.!?").strip()
    return re.sub(r"\s+", " ", value).lower()


def fence_mask(lines: Sequence[str]) -> List[bool]:
    """True for every line that is part of a fenced code block, fences included."""
    mask: List[bool] = []
    open_fence: Optional[str] = None
    for line in lines:
        m = FENCE_RE.match(line)
        if open_fence is None:
            if m:
                open_fence = m.group(1)[0] * 3
                mask.append(True)
            else:
                mask.append(False)
            continue
        mask.append(True)
        if m and line.strip().startswith(open_fence):
            open_fence = None
    return mask


def headings(lines: Sequence[str], mask: Sequence[bool]) -> List[Tuple[int, int, str]]:
    found = []
    for i, line in enumerate(lines):
        if mask[i]:
            continue
        m = HEADING_RE.match(line)
        if m:
            found.append((i, len(m.group(1)), m.group(2).strip()))
    return found


def entry_level(found: Sequence[Tuple[int, int, str]]) -> Optional[int]:
    if not found:
        return None
    levels = [level for _, level, _ in found]
    counts: Dict[int, int] = {}
    for level in levels:
        counts[level] = counts.get(level, 0) + 1
    # A single leading h1 is the section title; entries are one level below.
    if found[0][1] == 1 and counts.get(1) == 1 and len(levels) > 1:
        rest = levels[1:]
        counts = {}
        for level in rest:
            counts[level] = counts.get(level, 0) + 1
    repeated = [level for level, count in counts.items() if count >= 2]
    if repeated:
        return min(repeated)
    return min(counts) if counts else None


def split_row(line: str) -> List[str]:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [cell.strip() for cell in line.split("|")]


def split_label(line: str) -> Tuple[Optional[str], str]:
    m = LABEL_RE.match(line)
    if m:
        key = ALIASES.get(normalize_label(m.group(1)))
        if key:
            value = m.group(2).strip()
            value = re.sub(r"^(\*\*|__|\*|_)[ \t]*", "", value).strip()
            return key, value
    m = LABEL_ONLY_RE.match(line)
    if m:
        key = ALIASES.get(normalize_label(m.group(1)))
        if key:
            return key, ""
    return None, ""


def table_entries(
    lines: Sequence[str], mask: Sequence[bool], source: Path, fallback_heading: str
) -> List[Tuple[Entry, Dict[str, str]]]:
    rows: List[Tuple[int, str]] = []
    for i, line in enumerate(lines):
        if not mask[i] and line.strip().startswith("|"):
            rows.append((i, line))
    if len(rows) < 3:
        return []
    header = split_row(rows[0][1])
    if not TABLE_SEPARATOR_RE.match(rows[1][1]):
        return []
    columns: Dict[str, int] = {}
    for index, cell in enumerate(header):
        key = ALIASES.get(normalize_label(cell))
        if key and key not in columns:
            columns[key] = index
    if "meaning" not in columns or "action" not in columns:
        return []
    out = []
    for line_no, line in rows[2:]:
        cells = split_row(line)
        if not any(cells):
            continue
        values: Dict[str, str] = {}
        for key, index in columns.items():
            if index < len(cells):
                values[key] = cells[index]
        heading = values.get("message") or fallback_heading
        entry = Entry(source=source, line=line_no + 1, heading=heading)
        for key in ("meaning", "action"):
            if not values.get(key):
                entry.missing.append(key)
        out.append((entry, values))
    return out


def heading_entries(
    lines: Sequence[str], mask: Sequence[bool], found: Sequence[Tuple[int, int, str]], level: int, source: Path
) -> List[Entry]:
    entries: List[Entry] = []
    for position, (line_no, heading_level, heading_text) in enumerate(found):
        if heading_level != level:
            continue
        body_end = len(lines)
        for other_line, other_level, _ in found[position + 1 :]:
            if other_level <= level:
                body_end = other_line
                break
        body = lines[line_no + 1 : body_end]
        body_mask = mask[line_no + 1 : body_end]
        labels: List[Tuple[int, str, str]] = []
        for offset, body_line in enumerate(body):
            if body_mask[offset]:
                continue
            key, value = split_label(body_line)
            if key:
                labels.append((offset, key, value))
        label_lines = {offset for offset, _, _ in labels}
        found_parts = {key: value for _, key, value in labels}
        entry = Entry(source=source, line=line_no + 1, heading=heading_text)

        generic = normalize_heading(heading_text) in GENERIC_HEADINGS
        if "message" not in found_parts:
            if not QUOTE_RE.search(heading_text) and generic:
                entry.missing.append("message")
        for key in ("meaning", "action"):
            if key not in found_parts:
                entry.missing.append(key)
                continue
            if found_parts[key]:
                continue
            # A bare label ("What it means" on its own line) needs text below it.
            index = next(offset for offset, k, _ in labels if k == key)
            start = index + 1
            stop = min([line for line in label_lines if line > index], default=len(body))
            has_text = any(
                body[line].strip() and line not in label_lines for line in range(start, stop)
            )
            if not has_text:
                entry.missing.append(key)
        entries.append(entry)
    return entries


def analyse_section(section: Section) -> List[Entry]:
    text = section.text
    lines = text.split("\n")
    mask = fence_mask(lines)
    found = headings(lines, mask)
    level = entry_level(found)
    entries: List[Entry] = []
    if level is not None:
        entries = heading_entries(lines, mask, found, level, section.path)
    fallback = found[0][2] if found else ""
    tables = [entry for entry, _ in table_entries(lines, mask, section.path, fallback)]
    if tables and (not entries or all(normalize_heading(entry.heading) in GENERIC_HEADINGS for entry in entries)):
        return tables
    return entries


def demote_headings(text: str) -> str:
    lines = text.split("\n")
    mask = fence_mask(lines)
    found = headings(lines, mask)
    if not found or min(level for _, level, _ in found) != 1:
        return text
    out = list(lines)
    for line_no, level, heading_text in found:
        new_level = min(level + 1, 6)
        out[line_no] = "#" * new_level + " " + heading_text
    return "\n".join(out)


def clean_section(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = [line.rstrip() for line in text.split("\n")]
    text = "\n".join(lines)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip("\n")


def word_count(text: str) -> int:
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’\-]*", text))


def section_id(path: Path) -> Optional[str]:
    m = re.match(r"(?i)^(a\d{2})(?:[^0-9a-z]|$)", path.stem)
    return m.group(1).lower() if m else None


def discover(sections_dir: Path) -> Tuple[Dict[str, Section], List[Path]]:
    sections: Dict[str, Section] = {}
    ignored: List[Path] = []
    for path in sorted(sections_dir.glob("*.md")):
        if path.name.startswith(("_", ".")):
            ignored.append(path)
            continue
        sid = section_id(path)
        if sid is None:
            ignored.append(path)
            continue
        if sid in sections:
            raise SystemExit(
                "assemble.py: two section files for %s: %s and %s"
                % (sid, sections[sid].path.name, path.name)
            )
        sections[sid] = Section(sid=sid, path=path, text=path.read_text(encoding="utf-8-sig"))
    return sections, ignored


def build_doc(doc: Doc, sections: Dict[str, Section], demote: bool) -> Tuple[Optional[str], List[str]]:
    parts: List[str] = []
    used: List[str] = []
    for sid in doc.ids:
        section = sections.get(sid)
        if section is None:
            continue
        text = clean_section(section.text)
        if not text:
            continue
        if demote:
            text = demote_headings(text)
        parts.append(text)
        used.append(sid)
    if not parts:
        return None, used
    separator = "\n\n---\n\n" if doc.rule else "\n\n"
    body = "\n\n".join([HEADER_COMMENT, doc.title, doc.intro, separator.join(parts)])
    return body.rstrip("\n") + "\n", used


def write_if_changed(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return True


def format_report(
    results: Sequence[Tuple[Doc, List[str], Optional[str]]],
    gaps: Sequence[Entry],
    warnings: Sequence[str],
    ignored: Sequence[Path],
    checked: int,
) -> str:
    lines = [
        "# T13 assembly report",
        "",
        "Generated by `agents/T13/assemble.py`.",
        "",
        "## Documents",
        "",
        "| File | Sections used | Words |",
        "| --- | --- | --- |",
    ]
    for doc, used, text in results:
        words = word_count(text) if text else 0
        lines.append("| `%s` | %s | %d |" % (doc.filename, ", ".join(used) or "none", words))
    lines += ["", "## Troubleshooting check", "", "%d entries checked." % checked, ""]
    if gaps:
        lines.append("### Gaps")
        lines.append("")
        for entry in gaps:
            missing = ", ".join(PART_NAMES[part] for part in entry.missing)
            lines.append("- `%s:%d` entry %r is missing: %s" % (entry.source, entry.line, entry.heading, missing))
    else:
        lines.append("Every entry has the message, what it means and what to do.")
    if warnings:
        lines += ["", "### Warnings", ""] + ["- " + warning for warning in warnings]
    if ignored:
        lines += ["", "### Ignored files", ""] + [
            "- `%s` (not named aNN.md)" % path.name for path in ignored
        ]
    return "\n".join(lines) + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Merge agents/T13/sections/*.md into BETA.md, TROUBLESHOOTING.md and FAQ.md."
    )
    parser.add_argument("--root", help="repository root (default: two levels above this script)")
    parser.add_argument("--sections", help="section directory (default: <root>/agents/T13/sections)")
    parser.add_argument("--out", help="output directory (default: <root>/agents/T13)")
    parser.add_argument("--check", action="store_true", help="validate only, write nothing, exit 1 on gaps")
    parser.add_argument("--strict", action="store_true", help="exit 1 when entries have gaps")
    parser.add_argument("--report", help="write a markdown gap report to this path")
    parser.add_argument("--no-demote", action="store_true", help="keep section heading levels as written")
    parser.add_argument("--list", action="store_true", help="list the sections that were found and exit")
    parser.add_argument("--quiet", action="store_true", help="only print problems")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve() if args.root else Path(__file__).resolve().parents[2]
    sections_dir = Path(args.sections) if args.sections else root / "agents" / "T13" / "sections"
    out_dir = Path(args.out) if args.out else root / "agents" / "T13"

    if not sections_dir.is_dir():
        print("assemble.py: no section directory at %s" % sections_dir, file=sys.stderr)
        return 2

    sections, ignored = discover(sections_dir)
    if not sections:
        print("assemble.py: no sections in %s" % sections_dir, file=sys.stderr)
        return 1

    if args.list:
        for sid in sorted(sections):
            print("%s  %s" % (sid, sections[sid].path))
        for path in ignored:
            print("ignored  %s" % path)
        return 0

    warnings: List[str] = []
    gaps: List[Entry] = []
    checked = 0

    known = set(GUIDE_IDS + TROUBLE_IDS + FAQ_IDS)
    for sid in sorted(sections):
        if sid not in known:
            warnings.append("section %s is not part of BETA.md, TROUBLESHOOTING.md or FAQ.md" % sid)
        if not clean_section(sections[sid].text):
            warnings.append("section %s is empty" % sid)

    for doc in DOCS:
        for sid in doc.ids:
            if sid not in sections:
                warnings.append("missing section %s for %s" % (sid, doc.filename))

    seen_messages: Dict[str, str] = {}
    for sid in TROUBLE_IDS:
        section = sections.get(sid)
        if section is None:
            continue
        entries = analyse_section(section)
        if not entries:
            warnings.append("section %s has no troubleshooting entries (check the entry format)" % sid)
        checked += len(entries)
        for entry in entries:
            if entry.missing:
                gaps.append(entry)
            key = normalize_heading(entry.heading)
            if key and key in seen_messages:
                warnings.append(
                    "duplicate message %r in %s and %s" % (entry.heading, seen_messages[key], sid)
                )
            elif key:
                seen_messages[key] = sid

    results: List[Tuple[Doc, List[str], Optional[str]]] = []
    for doc in DOCS:
        text, used = build_doc(doc, sections, demote=not args.no_demote)
        results.append((doc, used, text))
        if text is None:
            warnings.append("no sections for %s, not written" % doc.filename)
            continue
        target = out_dir / doc.filename
        if args.check:
            if not args.quiet:
                print("would write %s (%d words)" % (target, word_count(text)))
        else:
            changed = write_if_changed(target, text)
            if not args.quiet:
                print(
                    "%s %s (%d words, sections %s)"
                    % ("wrote" if changed else "unchanged", target, word_count(text), ", ".join(used))
                )

    if gaps:
        print("", file=sys.stderr)
        print("Troubleshooting gaps (%d of %d entries):" % (len(gaps), checked), file=sys.stderr)
        for entry in gaps:
            missing = ", ".join(PART_NAMES[part] for part in entry.missing)
            print(
                "  %s:%d  %r  missing: %s" % (entry.source, entry.line, entry.heading, missing),
                file=sys.stderr,
            )
    for warning in warnings:
        print("warning: %s" % warning, file=sys.stderr)

    if args.report:
        report = format_report(results, gaps, warnings, ignored, checked)
        write_if_changed(Path(args.report), report)
        if not args.quiet:
            print("wrote %s" % args.report)

    if not args.quiet:
        print("%d sections, %d troubleshooting entries, %d gaps" % (len(sections), checked, len(gaps)))

    if args.check or args.strict:
        return 1 if gaps else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
