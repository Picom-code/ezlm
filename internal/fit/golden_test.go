package fit

// Golden plans: a stable table of machine profile -> plan, so a change to the
// planner shows up as a reviewable diff instead of a silently different pick.
//
// The table lives in testdata/golden_profiles.json, one line per profile and
// preference. After an intentional planner change, regenerate it and read the
// diff:
//
//	go test ./internal/fit -run TestGoldenProfiles -update-golden
//
// If testdata/profiles.json exists (the team's shared profile table), its
// profiles are covered too, so the golden file stays the team's full table.

import (
	"encoding/json"
	"flag"
	"math"
	"os"
	"sort"
	"strings"
	"testing"

	"github.com/picom-code/ezlm/internal/scan"
)

var updateGolden = flag.Bool("update-golden", false, "rewrite testdata/golden_profiles.json from the planner's current picks")

const goldenPath = "testdata/golden_profiles.json"

// goldenPlan is the part of a Plan a reviewer cares about: the decision, not
// the byte accounting (the invariant tests own that).
type goldenPlan struct {
	Model string   `json:"model"`
	Quant string   `json:"quant"`
	Ctx   int      `json:"ctx"`
	KV    string   `json:"kv"`
	Mode  Mode     `json:"mode"`
	NGL   int      `json:"ngl"`
	NCMOE int      `json:"ncmoe"`
	Spec  string   `json:"spec,omitempty"`
	Tok   int      `json:"tok"` // tok/s, rounded: calibration changes are diffs too
	Args  []string `json:"args,omitempty"`
}

func goldenOf(p Plan, ok bool) string {
	if !ok {
		return "null" // nothing fits on this machine for this preference
	}
	g := goldenPlan{Model: p.Model.ID, Quant: p.Quant.Name, Ctx: p.Ctx, KV: p.KV, Mode: p.Mode,
		NGL: p.NGL, NCMOE: p.NCPUMoE, Spec: p.Spec, Tok: int(math.Round(p.TokPerSec)), Args: p.Args()}
	b, err := json.Marshal(g)
	if err != nil {
		panic("golden: " + err.Error())
	}
	return string(b)
}

// TestGoldenProfiles pins the recommended plan for every profile in the
// golden file. It fails on a changed pick, on a profile that lost its entry
// (the plan disappeared) and on a stale entry (the profile was renamed).
func TestGoldenProfiles(t *testing.T) {
	c := cat(t)
	cases := goldenProfiles(t)
	got := map[string]string{}
	for name, hw := range cases {
		b := ComputeBudgets(hw, hw.RAMAvail)
		for _, pref := range []Pref{Balanced, Smartest, Fastest} {
			p, ok := Recommend(PlansFor(hw, c, b, pref))
			got[name+"/"+string(pref)] = goldenOf(p, ok)
		}
	}

	if *updateGolden {
		writeGolden(t, got)
		return
	}

	want := readGolden(t)
	var changed []string
	for _, key := range sortedKeys(got) {
		w, ok := want[key]
		if !ok {
			changed = append(changed, key+": missing from golden file")
			continue
		}
		if w != got[key] {
			changed = append(changed, key+":\n  got  "+got[key]+"\n  want "+w)
		}
	}
	for _, key := range sortedKeys(want) {
		if _, ok := got[key]; !ok {
			changed = append(changed, key+": stale entry, no such profile in the test table")
		}
	}
	if len(changed) > 0 {
		t.Errorf("planner picks differ from %s for %d of %d entries.\n"+
			"If the change is intended, run: go test ./internal/fit -run TestGoldenProfiles -update-golden\n%s",
			goldenPath, len(changed), len(got), strings.Join(changed, "\n"))
	}
}

// writeGolden rewrites the file in sorted order, one compact JSON object per
// line, so a planner change touches only the lines it changes.
func writeGolden(t *testing.T, got map[string]string) {
	t.Helper()
	var b strings.Builder
	b.WriteString("{\n")
	b.WriteString("  \"note\": \"Generated by TestGoldenProfiles -update-golden. One line per profile and preference; review the diff, do not hand-edit.\",\n")
	b.WriteString("  \"plans\": {\n")
	keys := sortedKeys(got)
	for i, key := range keys {
		k, err := json.Marshal(key)
		if err != nil {
			t.Fatal(err)
		}
		b.WriteString("    " + string(k) + ": " + got[key])
		if i < len(keys)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString("  }\n}\n")
	if err := os.MkdirAll("testdata", 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(goldenPath, []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %s: %d plans across %d profiles", goldenPath, len(got), len(got)/3)
}

func readGolden(t *testing.T) map[string]string {
	t.Helper()
	b, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("%s: %v (run: go test ./internal/fit -run TestGoldenProfiles -update-golden)", goldenPath, err)
	}
	var f struct {
		Plans map[string]json.RawMessage `json:"plans"`
	}
	if err := json.Unmarshal(b, &f); err != nil {
		t.Fatalf("%s is not valid JSON: %v", goldenPath, err)
	}
	if len(f.Plans) == 0 {
		t.Fatalf("%s has no plans (run: go test ./internal/fit -run TestGoldenProfiles -update-golden)", goldenPath)
	}
	out := map[string]string{}
	for k, v := range f.Plans {
		out[k] = string(v)
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// goldenProfiles is the machine table: the profiles a beta tester is likely
// to have, grouped like the team's hardware slices. Names are the keys in the
// golden file, so rename one and the old entry shows up as stale.
func goldenProfiles(t *testing.T) map[string]*scan.Hardware {
	cases := map[string]*scan.Hardware{
		// One NVIDIA card, 4 to 32 GB, laptop and desktop (a01).
		"nvidia-gtx-1650-4gb":        goldenDiscrete(scan.CUDA, "linux", "nvidia", "GeForce GTX 1650", 4, 3, 16, 10, 128),
		"nvidia-rtx-3050-laptop-6gb": goldenDiscrete(scan.CUDA, "windows", "nvidia", "GeForce RTX 3050 Laptop", 6, 5, 16, 9, 192),
		"nvidia-rtx-4060-8gb":        goldenDiscrete(scan.CUDA, "windows", "nvidia", "GeForce RTX 4060", 8, 7, 16, 9, 272),
		"nvidia-rtx-4070-super-12gb": goldenDiscrete(scan.CUDA, "windows", "nvidia", "GeForce RTX 4070 SUPER", 12, 11, 62, 42, 504),
		"nvidia-rtx-4090-24gb":       goldenDiscrete(scan.CUDA, "linux", "nvidia", "GeForce RTX 4090", 24, 23, 96, 80, 1008),
		"nvidia-rtx-5090-32gb":       goldenDiscrete(scan.CUDA, "windows", "nvidia", "GeForce RTX 5090", 32, 31, 128, 110, 1792),

		// A card partly used by another app: free memory far below the size (a06).
		"nvidia-rtx-4070-super-12gb-busy": goldenDiscrete(scan.CUDA, "windows", "nvidia", "GeForce RTX 4070 SUPER", 12, 4, 32, 20, 504),

		// Two and three cards, equal and mixed free memory (a02).
		"nvidia-2x-rtx-3060-12gb":          goldenMulti(scan.CUDA, "GeForce RTX 3060", []goldenCard{{12, 11}, {12, 11}}, 64, 50, 360),
		"nvidia-2x-rtx-4090-24gb-one-busy": goldenMulti(scan.CUDA, "GeForce RTX 4090", []goldenCard{{24, 23}, {24, 9}}, 128, 100, 1008),
		"nvidia-3x-mixed-3090-4090":        goldenMulti(scan.CUDA, "GeForce RTX", []goldenCard{{24, 23}, {24, 22}, {24, 20}}, 128, 100, 936),
		"nvidia-8x-h200":                   goldenMulti(scan.CUDA, "H200", []goldenCard{{141, 140}, {141, 140}, {141, 140}, {141, 140}, {141, 140}, {141, 140}, {141, 140}, {141, 140}}, 2048, 1900, 4800),

		// AMD and Intel through Vulkan (a03).
		"amd-radeon-rx-7800-xt-16gb": goldenDiscrete(scan.Vulkan, "windows", "amd", "AMD Radeon RX 7800 XT", 16, 15, 32, 24, 624),
		"amd-radeon-rx-6600-8gb":     goldenDiscrete(scan.ROCm, "linux", "amd", "AMD Radeon RX 6600", 8, 7, 16, 12, 224),
		"intel-arc-a770-16gb":        goldenDiscrete(scan.Vulkan, "windows", "intel", "Intel Arc A770", 16, 14, 32, 24, 560),

		// Apple Silicon, unified memory, 8 to 256 GB (a04).
		"apple-m1-8gb":         goldenMac(8, 4, 68),
		"apple-m3-pro-18gb":    goldenMac(18, 9, 150),
		"apple-m4-max-64gb":    goldenMac(64, 50, 546),
		"apple-m4-max-128gb":   goldenMac(128, 110, 546),
		"apple-m5-max-128gb":   goldenMac(128, 110, 614),
		"apple-m3-ultra-256gb": goldenMac(256, 230, 819),

		// Processor only, 16 to 64 GB (a05).
		"cpu-only-16gb": goldenCPU(16, 9, 50, 6),
		"cpu-only-64gb": goldenCPU(64, 50, 60, 12),

		// Windows on Arm: 96 GB shared-memory GPU behind 30 GB of RAM (a06).
		"windows-arm-rtx-spark-96gb-gpu-30gb-ram": goldenDiscrete(scan.CUDA, "windows", "nvidia", "RTX Spark N1X", 96, 90, 30, 20, 273),
	}

	// The shared profile table is another agent's file: take it when it is
	// there and readable, but never fail this test because of its shape.
	for name, hw := range sharedProfiles(t) {
		if _, ok := cases[name]; !ok {
			cases[name] = hw
		}
	}
	return cases
}

type goldenCard struct{ total, free uint64 } // GB

func goldenDiscrete(backend scan.Backend, osName, vendor, gpu string, vramTotal, vramFree, ramTotal, ramAvail uint64, bw float64) *scan.Hardware {
	free := vramFree * G
	return &scan.Hardware{OS: osName, Backend: backend, RAMTotal: ramTotal * G, RAMAvail: ramAvail * G,
		GPUUsable: free, DiskFree: 800 * G, CPUBandwidth: 60, PhysCores: 8,
		GPUs: []scan.GPU{{Name: gpu, Vendor: vendor, MemTotal: vramTotal * G, MemFree: free, Bandwidth: bw}}}
}

func goldenMulti(backend scan.Backend, gpu string, cards []goldenCard, ramTotal, ramAvail uint64, bw float64) *scan.Hardware {
	h := &scan.Hardware{OS: "linux", Backend: backend, RAMTotal: ramTotal * G, RAMAvail: ramAvail * G,
		DiskFree: 2000 * G, CPUBandwidth: 200, PhysCores: 32}
	for _, c := range cards {
		free := c.free * G
		h.GPUs = append(h.GPUs, scan.GPU{Name: gpu, Vendor: "nvidia", MemTotal: c.total * G, MemFree: free, Bandwidth: bw})
		h.GPUUsable += free
	}
	return h
}

// goldenMac mirrors how the scan reports an Apple machine: one shared pool,
// with the GPU allowed to wire a share of total RAM.
func goldenMac(ramGB, availGB uint64, bw float64) *scan.Hardware {
	usable := uint64(float64(ramGB*G) * 0.67)
	if ramGB > 36 {
		usable = uint64(float64(ramGB*G) * 0.75)
	}
	return &scan.Hardware{OS: "darwin", Backend: scan.Metal, Unified: true, RAMTotal: ramGB * G, RAMAvail: availGB * G,
		GPUUsable: usable, DiskFree: 500 * G, CPUBandwidth: bw, PhysCores: 10,
		GPUs: []scan.GPU{{Name: "Apple M-series", Vendor: "apple", Bandwidth: bw}}}
}

func goldenCPU(ramTotal, ramAvail uint64, bw float64, cores int) *scan.Hardware {
	return &scan.Hardware{OS: "linux", Backend: scan.CPU, RAMTotal: ramTotal * G, RAMAvail: ramAvail * G,
		DiskFree: 800 * G, CPUBandwidth: bw, PhysCores: cores}
}

// sharedProfiles reads testdata/profiles.json, the team's canonical profile
// table, if it exists. Three shapes are accepted: a map of name to
// scan.Hardware, {"profiles": {name: hardware}}, or a list of
// {name, hardware}. Anything else is skipped with a log line, because that
// file is owned by another agent.
func sharedProfiles(t *testing.T) map[string]*scan.Hardware {
	t.Helper()
	b, err := os.ReadFile("testdata/profiles.json")
	if err != nil {
		return nil
	}
	out := map[string]*scan.Hardware{}
	var flat map[string]scan.Hardware
	if err := json.Unmarshal(b, &flat); err == nil && len(flat) > 0 {
		for name, hw := range flat {
			out[name] = ptr(hw)
		}
		return out
	}
	var wrapped struct {
		Profiles map[string]scan.Hardware `json:"profiles"`
	}
	if err := json.Unmarshal(b, &wrapped); err == nil && len(wrapped.Profiles) > 0 {
		for name, hw := range wrapped.Profiles {
			out[name] = ptr(hw)
		}
		return out
	}
	var list []struct {
		Name     string        `json:"name"`
		Hardware scan.Hardware `json:"hardware"`
	}
	if err := json.Unmarshal(b, &list); err == nil && len(list) > 0 {
		for _, p := range list {
			hw := p.Hardware
			// A list that carries the hardware inline leaves this struct
			// empty: ignore those rather than pin zero-value machines.
			if p.Name != "" && (hw.Backend != "" || hw.RAMTotal > 0 || len(hw.GPUs) > 0) {
				out[p.Name] = &hw
			}
		}
		return out
	}
	t.Logf("testdata/profiles.json: unrecognised shape, skipped (golden covers the built-in table only)")
	return nil
}

func ptr(hw scan.Hardware) *scan.Hardware { return &hw }
